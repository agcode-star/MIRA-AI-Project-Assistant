// Planner Agent – parses the model output, verifies grounding against the source data,
// renders Markdown for the PM, and describes the LangSmith trace for this request.

const kb = $('Knowledge Base').first().json;
const requests = $('Planner: Build Prompt').all();

const norm = (s) => String(s ?? '').toLowerCase().replace(/[^a-z0-9%]+/g, ' ').trim();
const list = (items) => (items.length ? items.map((x) => `- ${x}`).join('\n') : '- _None stated in the source._');
const sourcedList = (items) => (items.length
  ? items.map((x) => `- ${x.text}  \n  _Source: “${x.source_quote}”_`).join('\n')
  : '- _None stated in the source._');

// Every plan item must trace back to the source; phases must match the timeline exactly.
function groundingCheck(plan, req) {
  const issues = [];
  let checked = 0, grounded = 0;
  const source = norm(req.source_text);

  for (const key of ['objectives', 'scope', 'success_metrics', 'governance']) {
    for (const item of plan[key]) {
      checked++;
      if (item.source_quote && source.includes(norm(item.source_quote))) grounded++;
      else issues.push(`${key}: quote not found in source → “${item.source_quote}”`);
    }
  }

  if (req.uses_project_data) {
    const timeline = new Map(kb.timeline.map((p) => [p.phase, p]));
    const known = new Set(kb.milestones.map((m) => norm(m.milestone)));
    if (plan.phases.length !== kb.timeline.length) {
      issues.push(`phase count ${plan.phases.length} ≠ timeline ${kb.timeline.length}`);
    }
    for (const p of plan.phases) {
      checked++;
      const t = timeline.get(p.phase_number);
      const problems = [];
      if (!t) problems.push('phase not in timeline');
      else {
        if (norm(p.name) !== norm(t.phase_name)) problems.push(`name “${p.name}”`);
        if (p.start_date !== t.start_date || p.end_date !== t.end_date) problems.push(`dates ${p.start_date}→${p.end_date}`);
        const invented = p.milestones_deliverables.filter((m) => !known.has(norm(m)));
        if (invented.length) problems.push(`milestones not in timeline: ${invented.join('; ')}`);
      }
      if (problems.length) issues.push(`Phase ${p.phase_number}: ${problems.join(', ')}`);
      else grounded++;
    }
  }

  return { checked, grounded, score: checked ? grounded / checked : 1, issues };
}

function renderPlan(plan, req, grounding) {
  const statusOf = new Map(kb.timeline.map((p) => [p.phase, p.schedule_status]));
  const rows = plan.phases.map((p) =>
    `| ${p.phase_number}. ${p.name} | W${p.start_week}–W${p.end_week} | ${p.start_date} → ${p.end_date} | ` +
    `${p.key_activities.join('; ')} | ${p.milestones_deliverables.join('; ')} | ${req.uses_project_data ? statusOf.get(p.phase_number) ?? '—' : '—'} |`);
  const sources = req.uses_project_data ? 'project_description.txt, project_timeline.csv' : 'user request';
  return [
    `# Project Plan — ${plan.project_name}`,
    `_Generated by Mira · as of ${kb.facts.as_of_date} · Sources: ${sources}_`,
    '## Executive summary', plan.executive_summary,
    '## Objectives', sourcedList(plan.objectives),
    '## Scope', sourcedList(plan.scope),
    '## Timeline, milestones & deliverables',
    ['| Phase | Weeks | Dates | Key activities | Milestones / deliverables | Schedule status |',
      '|---|---|---|---|---|---|', ...rows].join('\n'),
    '## Success metrics', sourcedList(plan.success_metrics),
    '## Team & governance', sourcedList(plan.governance),
    '## Assumptions', list(plan.assumptions),
    '## Open questions for the PM', list(plan.open_questions),
    '---',
    `Grounding check: ${grounding.grounded}/${grounding.checked} items traced to source` +
      (grounding.issues.length ? `\n${grounding.issues.map((i) => `- ⚠ ${i}`).join('\n')}` : ' ✅'),
  ].join('\n\n');
}

function renderClarification(c) {
  return [
    '## More information needed before I can build a plan',
    c.reason,
    '**What I have so far**', list(c.known_information),
    '**What is missing**', list(c.missing_information),
    '**Please answer these questions**',
    c.questions.map((q, i) => `${i + 1}. ${q}`).join('\n'),
    '_No plan was generated, to avoid inventing scope, milestones or dates that you have not provided._',
  ].join('\n\n');
}

return $input.all().map((item, i) => {
  const req = requests[i].json;
  const body = item.json.body ?? item.json;
  const headers = item.json.headers ?? {};
  const finishedAt = new Date().toISOString();
  const content = body.choices?.[0]?.message?.content ?? '';

  let output = null, parseError = null;
  try { output = JSON.parse(content); } catch (e) { parseError = e.message; }

  let markdown, grounding = null;
  if (!output) {
    markdown = `⚠ Planner Agent returned unparseable output (${parseError}).\n\n${content}`;
  } else if (output.status === 'PLAN' && output.plan) {
    grounding = groundingCheck(output.plan, req);
    markdown = renderPlan(output.plan, req, grounding);
  } else {
    markdown = renderClarification(output.clarification ?? { reason: 'Insufficient detail.', known_information: [], missing_information: [], questions: [] });
  }

  // Model latency from OpenAI's header gives accurate per-call timing even when items run in sequence.
  const latencyMs = Number(headers['openai-processing-ms']) || (Date.parse(finishedAt) - Date.parse(req.started_at));
  const llmEnd = new Date(Date.parse(req.started_at) + latencyMs).toISOString();
  const usage = body.usage ?? {};
  const status = output?.status ?? 'ERROR';

  return {
    json: {
      test_id: req.test_id,
      query: req.query,
      checks: req.checks,
      agent: req.agent,
      status,
      uses_project_data: req.uses_project_data,
      phase_count: output?.plan?.phases?.length ?? 0,
      grounding,
      markdown,
      usage: { input_tokens: usage.prompt_tokens ?? 0, output_tokens: usage.completion_tokens ?? 0, total_tokens: usage.total_tokens ?? 0 },
      trace: {
        name: 'Mira',
        start_time: req.started_at,
        end_time: finishedAt,
        inputs: { query: req.query },
        outputs: { status, response: markdown },
        tags: ['mira', 'planner', req.test_id].filter(Boolean),
        metadata: { test_id: req.test_id, agent: req.agent, status, uses_project_data: req.uses_project_data, groundedness: grounding?.score ?? null, as_of_date: kb.facts.as_of_date },
        children: [
          {
            name: req.agent,
            run_type: 'llm',
            start_time: req.started_at,
            end_time: llmEnd,
            inputs: { messages: req.openaiRequest.messages },
            outputs: body,
            model: req.openaiRequest.model,
            temperature: req.openaiRequest.temperature,
          },
          {
            name: 'Grounding Check',
            run_type: 'chain',
            start_time: llmEnd,
            end_time: finishedAt,
            inputs: { status, uses_project_data: req.uses_project_data },
            outputs: grounding ?? { skipped: 'no plan generated' },
          },
        ],
      },
    },
  };
});
