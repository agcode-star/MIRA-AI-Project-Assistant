// Milestone Tracker – renders milestone and deadline-risk tables from the computed tracker, verifies
// the narrative (task IDs, numbers, dates) and describes the LangSmith trace.

const kb = $('Knowledge Base').first().json;
const cfg = $('Config').first().json;
const requests = $('Milestone Tracker: Build Prompt').all();
const f = kb.facts;
const byId = new Map(kb.tasks.map((t) => [t.task_id, t]));
const cell = (s) => String(s ?? '').replace(/\|/g, '/').replace(/\n/g, ' ');
const ICON = { Blocked: '⛔', Overdue: '⚠', 'At risk': '🟠', 'Due soon': '🕒' };
const MS_ICON = { 'At risk': '🟠 At risk', 'In progress': '🔵 In progress', 'Tasks done': '🟢 Tasks done', 'No linked tasks': '⚪ No linked tasks' };

function milestoneTable(list) {
  return ['| Milestone | Phase | Due | In | Status | Linked tasks |', '|---|---|---|---|---|---|',
    ...list.map((m) => `| ${cell(m.milestone)} | ${m.phase}. ${cell(m.phase_name)} | ${m.due_date} | ${m.days_from_as_of}d | ${MS_ICON[m.status]}` +
      `${m.threat_ids.length ? ` (${m.threat_ids.join(', ')})` : ''} | ${m.linked_task_ids.map((id) => `${id} (${byId.get(id).status})`).join(', ') || '—'} |`)].join('\n');
}

function taskTable(flagged) {
  const order = ['Blocked', 'Overdue', 'At risk', 'Due soon'];
  return ['| ID | Task | Owner | Priority | Status | Due | Risk |', '|---|---|---|---|---|---|---|',
    ...[...flagged].sort((a, b) => order.indexOf(a.risk) - order.indexOf(b.risk) || a.days_until_due - b.days_until_due)
      .map((x) => `| ${x.task_id} | ${cell(x.task_name)} | ${x.assignee} | ${x.priority} | ${x.status} | ${x.due_date} | ${ICON[x.risk]} **${x.risk}** – ${cell(x.reason)} |`)].join('\n');
}

const citedList = (items) => (items.length
  ? items.map((x) => `- ${x.text}${x.task_ids.length ? ` _(${x.task_ids.join(', ')})_` : ''}`).join('\n')
  : '- _None._');

function allowedFacts(tr) {
  const ids = new Set(tr.allowed_task_ids);
  const all = [...tr.milestones_in_window, ...tr.next_milestones];
  const nums = new Set([tr.window_days, Number(cfg.dueSoonDays), f.current_week, f.total_weeks,
    tr.milestones_in_window.length, tr.next_milestones.length, tr.flagged.length,
    ...['Blocked', 'Overdue', 'At risk', 'Due soon'].map((l) => tr.flagged.filter((x) => x.risk === l).length),
    ...all.map((m) => m.days_from_as_of), ...all.map((m) => m.phase),
    ...tr.allowed_task_ids.map((id) => Math.abs(byId.get(id).days_until_due))]);
  const dates = new Set([f.as_of_date, ...tr.window.split(' to '), ...all.map((m) => m.due_date),
    ...tr.allowed_task_ids.map((id) => byId.get(id).due_date)]);
  return { ids, nums, pcts: new Set(), dates };
}

return $input.all().map((item, i) => {
  const req = requests[i].json;
  const tr = req.tracker;
  const body = item.json.body ?? item.json;
  const headers = item.json.headers ?? {};
  const finishedAt = new Date().toISOString();

  let out = null, parseError = null;
  try { out = JSON.parse(body.choices?.[0]?.message?.content ?? ''); } catch (e) { parseError = e.message; }
  out = out ?? { headline: `⚠ Milestone Tracker returned unparseable output (${parseError}).`, summary: '', actions: [], escalations: [] };

  const items = [
    { where: 'headline', text: out.headline, task_ids: [] },
    { where: 'summary', text: out.summary, task_ids: [] },
    ...out.actions.map((x, k) => ({ where: `actions[${k + 1}]`, ...x })),
    ...out.escalations.map((x, k) => ({ where: `escalations[${k + 1}]`, ...x })),
  ];
  const grounding = checkNarrative(items, allowedFacts(tr), f.as_of_date.slice(0, 4));

  const milestones = [
    `## Milestones due in the next ${tr.window_days} days (${tr.window})`,
    tr.milestones_in_window.length ? milestoneTable(tr.milestones_in_window) : '_No milestones fall in this window._',
    ...(tr.next_milestones.length ? ['**Next milestones after the window**', milestoneTable(tr.next_milestones)] : []),
  ];
  const tasks = [
    '## Tasks blocked or at risk of missing their deadline',
    tr.flagged.length ? taskTable(tr.flagged) : '_No blocked, overdue or at-risk tasks._',
    `_Rules: Blocked = status Blocked · Overdue = past due and not done · At risk = not started and due within ${cfg.dueSoonDays} days · Due soon = in progress and due within ${cfg.dueSoonDays} days._`,
  ];
  const tasksFirst = /block|task|deadline|overdue|at risk/i.test(req.query) && !/milestone/i.test(req.query);
  const markdown = [
    '# Milestone & Deadline Tracker',
    `_Generated by Mira · as of ${f.as_of_date} (week ${f.current_week} of ${f.total_weeks}, ${f.current_phase}) · Sources: project_timeline.csv, sample_task_board.csv_`,
    `**${out.headline}**`,
    out.summary,
    ...(tasksFirst ? [...tasks, ...milestones] : [...milestones, ...tasks]),
    '## Recommended actions', citedList(out.actions),
    '## Escalations', citedList(out.escalations),
    '---',
    `Grounding check: ${grounding.grounded}/${grounding.checked} narrative items verified (tasks, numbers and dates match the data)` +
      (grounding.issues.length ? `\n${grounding.issues.map((x) => `- ⚠ ${x}`).join('\n')}` : ' ✅'),
  ].filter(Boolean).join('\n\n');

  const latencyMs = Number(headers['openai-processing-ms']) || (Date.parse(finishedAt) - Date.parse(req.started_at));
  const llmEnd = new Date(Date.parse(req.started_at) + latencyMs).toISOString();
  const usage = body.usage ?? {};
  const ids = (level) => tr.flagged.filter((x) => x.risk === level).map((x) => x.task_id).join(', ');

  return {
    json: {
      test_id: req.test_id,
      query: req.query,
      checks: req.checks,
      agent: req.agent,
      status: 'ALERTS',
      uses_project_data: true,
      upcoming_count: tr.milestones_in_window.length,
      blocked: ids('Blocked'),
      overdue: ids('Overdue'),
      grounding,
      markdown,
      usage: { input_tokens: usage.prompt_tokens ?? 0, output_tokens: usage.completion_tokens ?? 0, total_tokens: usage.total_tokens ?? 0 },
      trace: {
        name: 'Mira',
        start_time: req.started_at,
        end_time: finishedAt,
        inputs: { query: req.query },
        outputs: { status: 'ALERTS', response: markdown },
        tags: ['mira', 'milestone', req.test_id].filter(Boolean),
        metadata: { test_id: req.test_id, agent: req.agent, window_days: tr.window_days, groundedness: grounding.score, as_of_date: f.as_of_date },
        children: [
          {
            name: req.agent,
            run_type: 'llm',
            start_time: req.started_at,
            end_time: llmEnd,
            inputs: { messages: req.openaiRequest.messages },
            outputs: body,
            model: req.openaiRequest.model,
            temperature: req.openaiRequest.temperature,
          },
          {
            name: 'Grounding Check',
            run_type: 'chain',
            start_time: llmEnd,
            end_time: finishedAt,
            inputs: { window: tr.window },
            outputs: { ...grounding, flagged: tr.flagged.map((x) => `${x.task_id} ${x.risk}`) },
          },
        ],
      },
    },
  };
});
